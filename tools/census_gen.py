#!/usr/bin/env python3
"""Generates census_generated.cpp: a counting wrapper for every recompiled function in an address
range. The generated functions are weak aliases (`sub_X` -> `__imp__sub_X`), so a strong `sub_X`
here takes every direct and table call, counts it and runs the original. A reporter thread prints
the busiest functions every 5 s (calls per second and per presented frame, the swap function being
the frame counter). Used to find the game's Direct3D entry points (docs/native-renderer-plan.md M1).

    python3 tools/census_gen.py generated/default/cvhd_register.cpp src/census/census_generated.cpp \
        0x82600000 0x82660000 sub_826287A8
"""
import re
import sys

register_cpp, out_cpp, lo, hi, swap_fn = sys.argv[1], sys.argv[2], int(sys.argv[3], 16), int(sys.argv[4], 16), sys.argv[5]
addrs = sorted({int(m, 16) for m in re.findall(r'SetFunction\(0x([0-9A-Fa-f]{8}), sub_', open(register_cpp).read())
                if lo <= int(m, 16) < hi})
names = ['sub_%08X' % a for a in addrs]
swap_index = names.index(swap_fn) if swap_fn in names else -1

out = []
out.append('// Generated by tools/census_gen.py: call counters for %d functions in 0x%08X-0x%08X.' % (len(names), lo, hi))
out.append('#include <atomic>')
out.append('#include <chrono>')
out.append('#include <cstdint>')
out.append('#include <cstdio>')
out.append('#include <thread>')
out.append('#include <vector>')
out.append('#include <algorithm>')
out.append('#include <rex/ppc.h>')
out.append('#include <rex/logging.h>')
out.append('namespace {')
out.append('std::atomic<uint32_t> census_counts[%d];' % len(names))
out.append('const char* const census_names[%d] = {' % len(names))
for n in names:
    out.append('    "%s",' % n)
out.append('};')
out.append('constexpr int kSwapIndex = %d;' % swap_index)
out.append('void census_report_loop() {')
out.append('  std::vector<uint32_t> last(%d, 0);' % len(names))
out.append('  while (true) {')
out.append('    std::this_thread::sleep_for(std::chrono::seconds(5));')
out.append('    std::vector<std::pair<uint32_t, int>> deltas;')
out.append('    for (int i = 0; i < %d; i++) {' % len(names))
out.append('      uint32_t c = census_counts[i].load(std::memory_order_relaxed);')
out.append('      uint32_t d = c - last[i];')
out.append('      last[i] = c;')
out.append('      if (d) deltas.emplace_back(d, i);')
out.append('    }')
out.append('    std::sort(deltas.begin(), deltas.end(), [](auto& a, auto& b) { return a.first > b.first; });')
out.append('    uint32_t frames = 0;')
out.append('    for (auto& p : deltas) if (p.second == kSwapIndex) frames = p.first;')
out.append('    std::string line = "census (5 s, " + std::to_string(frames) + " frames): ";')
out.append('    int shown = 0;')
out.append('    for (auto& p : deltas) {')
out.append('      if (shown++ >= 60) break;')
out.append('      char buf[96];')
out.append('      std::snprintf(buf, sizeof(buf), "%s %u/s %.1f/f | ", census_names[p.second], p.first / 5, frames ? double(p.first) / frames : 0.0);')
out.append('      line += buf;')
out.append('    }')
out.append('    REXLOG_INFO("{} ({} distinct)", line, deltas.size());')
out.append('  }')
out.append('}')
out.append('struct CensusStart { CensusStart() { std::thread(census_report_loop).detach(); } } census_start;')
out.append('}  // namespace')
out.append('extern "C" {')
for i, n in enumerate(names):
    out.append('void __imp__%s(PPCContext& __restrict ctx, uint8_t* base);' % n)
    out.append('void %s(PPCContext& __restrict ctx, uint8_t* base) { census_counts[%d].fetch_add(1, std::memory_order_relaxed); __imp__%s(ctx, base); }' % (n, i, n))
out.append('}')
open(out_cpp, 'w', newline='\n').write('\n'.join(out) + '\n')
print('%d wrappers, swap index %d' % (len(names), swap_index))
